def _load(name, blob):
    m = types.ModuleType(name); m.__file__ = '<embedded %s>' % name
    sys.modules[name] = m
    exec(zlib.decompress(base64.b64decode(blob)).decode('utf-8'), m.__dict__)
    return m

wozPKG = _load('wozPKG', WOZPKG_BLOB)
wozDSC = _load('wozDSC', WOZDSC_BLOB)
wozHKX = _load('wozHKX', WOZHKX_BLOB)
wozTPL = _load('wozTPL', WOZTPL_BLOB)
wozFix = _load('wozFix', WOZFIX_BLOB)

def _log(lines, s=''):
    print(s); lines.append(s)

def load_order(a, lines):
    table = None
    if a.ref:
        table = wozDSC.learn_reference(wozDSC._load_reference(a.ref))
        _log(lines, 'learned PC order from %d reference package(s): %d key sets, %d keys' % (len(a.ref), len(table['sets']), len(table['rank'])))
        if a.save_table:
            json.dump(dict(sets=[[k.decode('latin1') for k in o] for o in table['sets'].values()],
                           rank={k.decode('latin1'): v for k, v in table['rank'].items()},
                           prior={k.decode('latin1'): sorted(v) for k, v in wozDSC.PRIOR.items()}), open(a.save_table, 'w'))
    elif a.table:
        j = json.load(open(a.table))
        table = dict(sets={frozenset(k.encode('latin1') for k in o): tuple(k.encode('latin1') for k in o) for o in j['sets']},
                     rank={k.encode('latin1'): v for k, v in j['rank'].items()})
        wozDSC.PRIOR = {k.encode('latin1'): set(v) for k, v in j.get('prior', {}).items()} or None
    return table

def convert_one(src, dst, a, table, lines):
    d, e, ents = wozPKG.read_pkg(src)
    _log(lines, '== %s' % os.path.basename(src))
    if e != '>':
        _log(lines, '   already a PC (little-endian) package - skipped'); return False
    hs = wozPKG.header_size(d, e)
    header = wozPKG.swap_header(d[:hs], '>', '<')
    out = []; st = {}; todo = {'.tpl': [], '.hkx': []}; unsure = []; failed = []; dropped = 0; fixlog = []
    def count(k): st[k] = st.get(k, 0) + 1
    for x in ents:
        path = x['pathbuf'].split(b'\0')[0].decode('latin1'); low = path.lower(); ext = os.path.splitext(low)[1]
        data = x['data']; pathbuf = x['pathbuf']
        if a.drop_256 and re.search(r'_256\.(tpl|rlet)$', low): dropped += 1; continue
        if ext == '.rlet':
            try:
                new = wozDSC.rlet_swap(data)
                if wozDSC.rlet_swap(new, '<') != data: raise ValueError('self-check failed')
                data = new; count('rlet converted')
            except Exception as ex: failed.append((path, str(ex))); count('FAILED')
        elif ext in wozDSC.BF_EXT and data[:8] == b'BFBINARY':
            try:
                _, tree = wozDSC.parse(data, '>'); s = {}
                if table: tree = wozDSC.reorder(tree, table, s)
                new = wozDSC.serialize(tree)
                _, t2 = wozDSC.parse(new, '<')
                if wozDSC.canon(t2) != wozDSC.canon(tree) or len(new) != len(data): raise ValueError('self-check failed')
                data = new; count('binary property file converted')
                if table is not None and s.get('unknown'): unsure.append((path, '%d map(s) with unseen keys' % s['unknown']))
            except Exception as ex: failed.append((path, str(ex))); count('FAILED')
        elif ext == '.tpl':
            stem = path[:-4]; found = None
            for ex2 in ('.dds', '.tga'):
                p = os.path.join(a.textures, stem + ex2) if a.textures else None
                if p and os.path.isfile(p): found = (stem + ex2, p); break
            if found:
                data = open(found[1], 'rb').read(); newp = found[0].encode('latin1')
                pathbuf = newp + b'\0' * (len(x['pathbuf']) - len(newp)); count('texture replaced from --textures folder')
            elif not a.keep_tpl:
                try:
                    newext, data = wozTPL.tpl_to_pc(data, os.path.basename(stem), a.dds_mode, not a.no_mips, path, tga_style='legacy' if a.tga_legacy else 'pc', tga_rle=not a.tga_raw)
                    newp = (stem + '.' + newext).encode('latin1')
                    pathbuf = newp + b'\0' * (len(x['pathbuf']) - len(newp)); count('texture converted to .' + newext)
                except Exception as ex:
                    todo['.tpl'].append((path, str(ex)[:60])); count('tpl NOT converted')
            else: todo['.tpl'].append(path); count('tpl NOT converted (--keep-tpl)')
        elif ext == '.hkx':
            p = os.path.join(a.hkx, path) if a.hkx else None
            if p and os.path.isfile(p): data = open(p, 'rb').read(); count('hkx replaced from --hkx folder')
            else:
                try: data = wozHKX.convert(data); count('hkx converted')
                except Exception as ex: todo['.hkx'].append((path, str(ex)[:60])); count('hkx NOT converted')
            for flag, key in ((a.penguin_hold_fix, 'hold'), (a.penguin_nursery_fix, 'nursery')):
                fpath, fn = wozFix.FIXES[key]
                if flag and low == fpath and path not in [q for q, _ in todo['.hkx']]:
                    try: data, msg = fn(data); count('optional fix applied: ' + key); fixlog.append('%s: %s' % (path, msg))
                    except wozFix.FixError as ex: count('optional fix NOT applied: ' + key); fixlog.append('NOT APPLIED %s: %s' % (path, ex))
        else: count('copied unchanged')
        out.append(dict(idx=0, typ=x['typ'], ord=0, pathbuf=pathbuf, data=data))
    for i, x in enumerate(out): x['idx'] = 0 if i == 0 else 1; x['ord'] = i + 1
    blob = wozPKG.build_pkg(header, out, '<', level=6, clean=True)   # level 6 = what the original packages use
    os.makedirs(os.path.dirname(os.path.abspath(dst)), exist_ok=True)
    open(dst, 'wb').write(blob)
    for k in sorted(st): _log(lines, '   %-34s %d' % (k, st[k]))
    if dropped: _log(lines, '   %-34s %d' % ('_256 variants left out', dropped))
    _log(lines, '   wrote %s (%d entries, PC format)' % (dst, len(out)))
    for m in fixlog: _log(lines, '   ' + m)
    for p, why in failed: _log(lines, '   FAILED (left unconverted): %s - %s' % (p, why))
    for p, why in unsure[:25]: _log(lines, '   check order: %s (%s)' % (p, why))
    if len(unsure) > 25: _log(lines, '   ... and %d more files with uncertain order' % (len(unsure) - 25))
    for k in ('.tpl', '.hkx'):
        if todo[k]:
            _log(lines, '   STILL WII FORMAT - %d %s file(s), the game will not read these correctly, e.g.:' % (len(todo[k]), k))
            for p in todo[k][:4]: _log(lines, '      ' + (p if isinstance(p, str) else '%s  (%s)' % p))
    return True

